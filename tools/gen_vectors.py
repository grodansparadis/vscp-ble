#!/usr/bin/env python3
"""Generate the shared interoperability vectors.

Writes tests/vectors/vectors.json (used by the Python tests and anyone
porting the codec) and tests/vectors/vectors.h (used by the C tests).

The frames are produced by the Python reference codec
(examples/linux-bluez/vscp_ble) with AES-CCM from python3-cryptography,
an implementation independent of the C library. The spec's own vectors
(E1 A/B, L0 4.4, F1 9.5) are included and checked.

Usage: tools/gen_vectors.py [--check]   (--check: fail if the files differ)
"""

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "examples" / "linux-bluez"))

from vscp_ble import (Event, a2_encode, e1_encode, f1_fragment, g1_control_encode, g1_fragments,  # noqa: E402
                      g1_record_encode, l0_encode)

GUID = bytes(range(16))
KEY = bytes(range(16))
PREFIX = bytes.fromhex("a0a1a2a3a4")


def ramp(n):
    return bytes(i % 256 for i in range(n))


def build():
    v = {"company": 0xFFFF, "guid": GUID.hex(), "a2_key": KEY.hex(), "a2_nonce_prefix": PREFIX.hex(),
         "e1": [], "l0": [], "a2": [], "f1": [], "g1": []}

    # E1 (spec 5.7 vectors A and B, plus maximum size)
    for name, seq, ev, spec in (
        ("e1_a", 0, Event(GUID, 0, 0), "21ffffff010000000000000102030405060708090a0b0c0d0e0f0000000000000000"),
        ("e1_b", 1, Event(GUID, 0x0A, 6, b"\x11\x22"),
         "23ffffff010000000001000102030405060708090a0b0c0d0e0f0000000a000600021122"),
        ("e1_max", 0xFFFFFFFF, Event(GUID, 0x0A, 6, ramp(222), 0x1234), None),
    ):
        frame = e1_encode(ev, seq)
        assert spec is None or frame.hex() == spec, name
        v["e1"].append(dict(name=name, sequence=seq, head=ev.head, vscp_class=ev.vscp_class,
                            vscp_type=ev.vscp_type, data=ev.data.hex(), frame=frame.hex()))

    # L0 (spec 4.4)
    frame = l0_encode(0x1234, 0x10, 0x0A, 6, b"\xaa\xbb")
    assert frame.hex() == "14ffffff00123410000a000602aabb000000000000"
    v["l0"].append(dict(name="l0_spec", node_id=0x1234, head=0x10, vscp_class=0x0A, vscp_type=6, data="aabb",
                        frame=frame.hex()))

    # A2 known-answer vectors (exact nonce and AAD construction)
    for name, kid, epoch, seq, ev in (
        ("a2_n3", 1, 1, 2, Event(GUID, 0x0A, 6, b"\x11\x22\x33")),
        ("a2_n0", 1, 0, 0, Event(GUID, 0x14, 3)),
        ("a2_max", 0x0102, 7, 0xFFFFFFFF, Event(GUID, 0x0A, 6, ramp(200), 0x00E0)),
    ):
        frame = a2_encode(ev, kid, epoch, seq, KEY, PREFIX)
        v["a2"].append(dict(name=name, key_id=kid, epoch=epoch, sequence=seq, head=ev.head,
                            vscp_class=ev.vscp_class, vscp_type=ev.vscp_type, data=ev.data.hex(),
                            frame=frame.hex()))
    assert v["a2"][0]["frame"].endswith("3c4532039788b44a4ad321c6493748c0f6c4d1")

    # F1 (spec 9.5)
    for name, t in (("f1_223", 223), ("f1_1024", 1024)):
        frags = f1_fragment(Event(GUID, 0x0A, 6, ramp(t)), 1)
        v["f1"].append(dict(name=name, message_id=1, head=0, vscp_class=0x0A, vscp_type=6, data=ramp(t).hex(),
                            fragments=[f.hex() for f in frags]))
    assert [f[0] for f in f1_fragment(Event(GUID, 0x0A, 6, ramp(223)), 1)] == [0xFD, 0x34]

    # G1 records and fragments
    for name, tid, ev, mtus in (
        ("g1_n3", 1, Event(GUID, 0x0A, 6, b"\x11\x22\x33"), (23, 247)),
        ("g1_max", 0xA5A5A5A5, Event(GUID, 0x0A, 6, ramp(487), 0x0003), (23, 185, 517)),
    ):
        rec = g1_record_encode(ev, tid)
        v["g1"].append(dict(name=name, tid=tid, head=ev.head, vscp_class=ev.vscp_class, vscp_type=ev.vscp_type,
                            data=ev.data.hex(), record=rec.hex(),
                            fragments={str(m): [f.hex() for f in g1_fragments(rec, m)] for m in mtus}))
    v["g1_hello"] = g1_control_encode(0x01, 0, 0, bytes.fromhex("01e70209" "0000")).hex()
    return v


def c_array(name, hexstr):
    data = bytes.fromhex(hexstr)
    body = ", ".join("0x%02x" % b for b in data) or "0"
    return "static const uint8_t %s[] = { %s };\nstatic const size_t %s_len = %d;\n" % (name, body, name, len(data))


def c_header(v):
    out = ["/* Generated by tools/gen_vectors.py - do not edit */\n",
           "#ifndef VSCP_BLE_TEST_VECTORS_H\n#define VSCP_BLE_TEST_VECTORS_H\n\n#include <stddef.h>\n#include <stdint.h>\n\n"]
    for kind in ("e1", "l0", "a2"):
        for e in v[kind]:
            out.append(c_array("v_%s_frame" % e["name"], e["frame"]))
    for e in v["f1"]:
        out.append("#define V_%s_COUNT %d\n" % (e["name"].upper(), len(e["fragments"])))
        for i, f in enumerate(e["fragments"]):
            out.append(c_array("v_%s_frag%d" % (e["name"], i), f))
    for e in v["g1"]:
        out.append(c_array("v_%s_record" % e["name"], e["record"]))
        for mtu, frags in e["fragments"].items():
            out.append("#define V_%s_MTU%s_COUNT %d\n" % (e["name"].upper(), mtu, len(frags)))
            for i, f in enumerate(frags):
                out.append(c_array("v_%s_mtu%s_frag%d" % (e["name"], mtu, i), f))
    out.append(c_array("v_g1_hello", v["g1_hello"]))
    out.append("\n#endif\n")
    return "".join(out)


def main():
    check = "--check" in sys.argv[1:]
    v = build()
    files = {ROOT / "tests" / "vectors" / "vectors.json": json.dumps(v, indent=1) + "\n",
             ROOT / "tests" / "vectors" / "vectors.h": c_header(v)}
    bad = 0
    for path, text in files.items():
        if check:
            if not path.exists() or path.read_text() != text:
                print("out of date: %s" % path.relative_to(ROOT))
                bad = 1
        else:
            path.write_text(text)
    return bad


if __name__ == "__main__":
    sys.exit(main())
